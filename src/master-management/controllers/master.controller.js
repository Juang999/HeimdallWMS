const { getDataFilteredByField } = require('../service/master.service');

class MasterController {
    getSizeGroup = (req, res) => {
        getDataFilteredByField('size-group')
        .then(result => {
            res.status(200)
                .json({
                    status: 'success',
                    message: 'ok',
                    data: result,
                    error: null
                })
        })
        .catch(err => {
            res.status(400)
                .json({
                    status: 'failed',
                    message: 'error',
                    data: null,
                    error: err.message
                })
        })
    }
}

module.exports = new MasterController();